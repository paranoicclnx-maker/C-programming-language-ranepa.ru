// Begin3±. Даны стороны прямоугольника a и b. Найти его площадь S = ab и периметр P = 2(a + b).

#include <stdio.h>
int main()
{

    int a,b,p; // объявление переменных (длина,ширина,периметр)
    printf("Введите длину и ширину прямоугольника"); // выводит текст 
    scanf("%d%d",&a,&b); // ввод пользователя 
    p = 2 * (a + b); // периметр = 2 * (длина + ширина)
    printf("Периметр прямоугольника = %d",p); // выводит текст и число в виде периметра
}