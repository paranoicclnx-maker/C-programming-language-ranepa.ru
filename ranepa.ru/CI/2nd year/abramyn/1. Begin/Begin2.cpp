// Begin2±. Дана сторона квадрата a. Найти его площадь S = a**2.

#include <stdio.h>


int main()
{

    int a,s;                            // обозначение переменных (сторона , площадь)
    printf("Введите длину стороны: "); // выводит текст 
    scanf("%d",&a);                    // Ввод данных от пользователя
    s = a * a;                         // площадь = сторона * сторона
    printf("Площадь квадрата составляет: %d",s); // выводит текст и площадь
    return 0;
}

