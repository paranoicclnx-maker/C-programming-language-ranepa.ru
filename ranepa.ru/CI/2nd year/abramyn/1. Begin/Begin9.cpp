/* Begin9±. Даны два неотрицательных числа a и b. Найти их среднее геометри-

ческое, то есть квадратный корень из их произведения: pab. */ 

#include <stdio.h>
#include <math.h>
int main()
{
    int a,b;
    double koren;
    printf("Введите 2 числа "); // вывод текста
    scanf("%d%d",&a,&b); // ввод данных от пользователя
    koren = sqrt(a * b ); // нахождение среднего числа из 2 чисел  б
    printf("среднее геометри-ческое этих чисел =  %f",koren); // вывод текста

}