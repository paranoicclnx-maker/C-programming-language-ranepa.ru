#include <stdio.h>
int main()
{
    int a,b;
    double sred;
    printf("Введите 2 числа "); // вывод текста
    scanf("%d%d",&a,&b); // ввод данных от пользователя
    sred = (a + b ) / 2; // нахождение среднего числа из 2 чисел  б
    printf("Среднее арифметическое этих чисел =  %f",sred); // вывод текста

}