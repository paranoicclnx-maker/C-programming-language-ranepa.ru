/* While3. Даны целые положительные числа N и K. 
Используя только операции сложения и вычитания, найти частное от деления нацело N на K, а также
остаток от этого деления */

#include <stdio.h>
int main()
{
int n,k;
int cel = 0;
scanf("%d%d",&n,&k);
    while (n > k) // число N > k пока верно цикл завершается
    {
        n = n - k; // нахождение остатка 
        cel++; // нахождение целых частей от отрезка N
    }
    printf("%d %d",cel,n);
    return 0;
}