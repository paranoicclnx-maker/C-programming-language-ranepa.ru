/* Дано целое число N (>1). Вывести наибольшее из целых чисел K,
для которых сумма 1 + 2 + ... + K будет меньше или равна N, и саму эту
сумму */
#include <stdio.h>

int main()
{
    int N;
    int S = 0; // сумма
    int K = 0; //  наибольшее число
    scanf("%d",&N);
    if(N > 1)
    {
    while (S + K + 1 <= N)
    {
        K = K + 1;
        S = S + K;
    }
}
    printf("%d %d",K,S);
}