// While2. Даны положительные числа A и B (A > B). На отрезке длины A размещено максимально возможное количество отрезков длины B (без наложе- 28ний). Не используя операции умножения и деления, найти количество отрезков B, размещенных на отрезке A.
#include <stdio.h>
int main()
{
	int a,b;
	scanf("%d%d",&a,&b);
	int n = 0;
	if(a > b){
		while(a >= b){
			a = a - b;
			n ++;
			
			
		}
		printf("%d",n);
		return 0;
	}
	
	
	
}
